"""
Dataset router.

Exposes the public API surface for dataset metadata.
All HTTP concerns (status codes, content negotiation, error responses)
live here; business logic is delegated to dataset_service.

FAIR alignment
--------------
Findable    : GET /datasets          — discover all datasets
Accessible  : GET /datasets/{title} — retrieve a single dataset by title
Interoperable: JSON responses with a stable, documented schema
Reusable    : rich OpenAPI docs auto-generated by FastAPI
"""

from __future__ import annotations

import logging
from urllib.parse import unquote

import httpx
from fastapi import APIRouter, HTTPException, Query, status
from fastapi.responses import JSONResponse

from models.dataset import DatasetListResponse, DatasetSummary
from services.dataset_service import fetch_all_datasets, fetch_dataset_by_title

logger = logging.getLogger(__name__)

router = APIRouter(
    prefix="/datasets",
    tags=["Datasets"],
)


# ---------------------------------------------------------------------------
# GET /datasets
# ---------------------------------------------------------------------------


@router.get(
    "",
    response_model=DatasetListResponse,
    summary="List all datasets",
    description=(
        "Returns metadata for all HDR UK datasets. "
        "Each record exposes **title**, **description**, "
        "**accessServiceCategory**, and a link to **accessRights** "
        "in line with FAIR data principles."
    ),
    responses={
        200: {"description": "Successful response — list of dataset summaries."},
        502: {"description": "Failed to fetch data from the upstream HDR UK source."},
    },
)
async def list_datasets(
    search: str | None = Query(
        default=None,
        description="Optional case-insensitive substring filter applied to dataset titles.",
        examples=["CPRD"],
    ),
) -> DatasetListResponse:
    """Return all datasets, optionally filtered by a title substring."""
    try:
        result = await fetch_all_datasets()
    except httpx.HTTPStatusError as exc:
        logger.error("Upstream HTTP error: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Unable to retrieve datasets from upstream source.",
        ) from exc
    except httpx.RequestError as exc:
        logger.error("Network error reaching upstream: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Network error when contacting upstream source.",
        ) from exc

    if search:
        search_lower = search.lower()
        filtered = [d for d in result.datasets if search_lower in d.title.lower()]
        return DatasetListResponse(count=len(filtered), datasets=filtered)

    return result


# ---------------------------------------------------------------------------
# GET /datasets/{title}
# ---------------------------------------------------------------------------


@router.get(
    "/{title}",
    response_model=DatasetSummary,
    summary="Get a dataset by title",
    description=(
        "Retrieve a single dataset whose title matches exactly (case-insensitive). "
        "URL-encode any spaces or special characters in the title."
    ),
    responses={
        200: {"description": "Dataset found."},
        404: {"description": "No dataset with that title exists."},
        502: {"description": "Failed to fetch data from the upstream HDR UK source."},
    },
)
async def get_dataset(title: str) -> DatasetSummary:
    """Return a single dataset by its exact title (case-insensitive)."""
    decoded_title = unquote(title)
    try:
        dataset = await fetch_dataset_by_title(decoded_title)
    except (httpx.HTTPStatusError, httpx.RequestError) as exc:
        logger.error("Upstream error: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Unable to retrieve datasets from upstream source.",
        ) from exc

    if dataset is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Dataset with title '{decoded_title}' not found.",
        )

    return dataset


# ---------------------------------------------------------------------------
# GET /datasets/health  (lightweight liveness probe for the router)
# ---------------------------------------------------------------------------


@router.get(
    "/health",
    include_in_schema=False,  # keep the OpenAPI docs clean
)
async def dataset_health() -> JSONResponse:
    return JSONResponse({"status": "ok"})